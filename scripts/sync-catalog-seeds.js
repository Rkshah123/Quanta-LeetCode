/* ---------------------- scripts / sync-catalog-seeds ---------------------- */
/* Rebuilds the problem list embedded in lab-notes.js from the database, so the
   app and the API can never disagree about a title or a difficulty.

   Why this exists
   ---------------
   The app ships a copy of the catalog inside lab-notes.js so it can show a
   problem list with no network at all. That copy is generated from the same
   database, but it was generated by hand once: a few dozen problems now carry
   a different difficulty in the app than in the database, which means
   "Hard" in the app and ?difficulty=Hard on the API return different counts.

   Usage:
     npm run sync:catalog              rewrite lab-notes.js
     npm run sync:catalog -- --check   report differences, change nothing

   The rewrite only replaces the generated entries between "return [" and the
   closing "];" of seedProblems(). Everything else in the file is left alone,
   and the file is not written at all unless something actually differs. */

require("dotenv").config({ path: require("path").join(__dirname, "..", ".env"), quiet: true });

const fs = require("fs");
const path = require("path");
const problemsRepo = require("../db/problems");
const { closePool } = require("../db/pool");

const TARGET = path.join(__dirname, "..", "lab-notes.js");
const checkOnly = process.argv.includes("--check");

const jsString = (value) => JSON.stringify(String(value ?? ""));

/* Whitespace and capitalisation are not worth "fixing" from the database: it
   carries a double space in one title and the wrong case in a few others, and
   copying those in would be a regression dressed up as a sync. A title is only
   replaced when it says something different, not when it merely looks
   different. */
const normaliseTitle = (value) => String(value ?? "").trim().replace(/\s+/g, " ").toLowerCase();

const readEmbedded = () => {
  const source = fs.readFileSync(TARGET, "utf8");
  const lines = source.split(/\r?\n/);
  const start = lines.findIndex((l) => l.includes("const seedProblems = () => {"));
  if (start < 0) throw new Error("seedProblems() was not found in lab-notes.js");
  const retIndex = lines.findIndex((l, i) => i > start && l.trim() === "return [");
  if (retIndex < 0) throw new Error("the generated list was not found in seedProblems()");
  let end = -1;
  for (let i = retIndex + 1; i < lines.length; i += 1) {
    if (/^\s{4}\];\s*$/.test(lines[i])) {
      end = i;
      break;
    }
  }
  if (end < 0) throw new Error("the end of the generated list was not found");

  const entries = [];
  for (let i = retIndex + 1; i < end; i += 1) {
    const match = lines[i].trim().match(/^p\((-?\d+),\s*(".*?"),\s*(".*?"),\s*("(?:Easy|Medium|Hard)")\)/);
    if (match) entries.push({ line: i, num: Number(match[1]), slug: JSON.parse(match[2]), title: JSON.parse(match[3]), difficulty: JSON.parse(match[4]) });
  }
  return { source, lines, retIndex, end, entries };
};

const main = async () => {
  console.log("Reading the catalog from the database...");
  const dbProblems = [];
  const pageSize = 100;
  for (let offset = 0; ; offset += pageSize) {
    const page = await problemsRepo.listProblems({ limit: pageSize, offset, sort: "catalog" });
    if (!page.items.length) break;
    dbProblems.push(...page.items);
    if (offset + page.items.length >= page.total) break;
  }
  console.log(`  ${dbProblems.length} problems read (the database reports the catalog as ${pageSize ? dbProblems.length : 0})`);

  const { lines, retIndex, end, entries } = readEmbedded();
  console.log(`  lab-notes.js currently embeds ${entries.length} problems`);

  const bySlug = new Map(dbProblems.map((p) => [p.slug, p]));
  const embeddedBySlug = new Map(entries.map((e) => [e.slug, e]));

  /* Two different kinds of difference, kept apart on purpose.
     - Titles and difficulties: the database is the catalogue of record, so the
       app takes them. Difficulty is what the filters use, so this is the part
       that actually fixes the wrong filter counts.
     - LeetCode numbers: the database is known to be wrong for a few rows
       (percentage-of-letter-in-string is stored as 2278 instead of 1633, and
       two more like it), so the app keeps the number it already has. The
       conflicts are reported instead of being applied. */
  const adopt = [];
  const numberConflicts = [];

  for (const entry of entries) {
    const match = bySlug.get(entry.slug);
    if (!match) {
      adopt.push({ ...entry, title: entry.title, difficulty: entry.difficulty });
      continue;
    }
    if (normaliseTitle(match.title) !== normaliseTitle(entry.title)) {
      adopt.push({ ...entry, title: String(match.title).trim().replace(/\s+/g, " "), difficulty: match.difficulty });
    } else if (match.difficulty !== entry.difficulty) {
      adopt.push({ ...entry, title: entry.title, difficulty: match.difficulty });
    } else {
      adopt.push({ ...entry, title: entry.title, difficulty: match.difficulty });
    }
    if ((match.num ?? null) !== entry.num) {
      numberConflicts.push(`${entry.slug}: app ${entry.num} vs database ${match.num ?? "none"} (kept the app's)`);
    }
  }

  const embeddedSlugs = new Set(entries.map((e) => e.slug));
  const missing = dbProblems.filter((p) => !embeddedSlugs.has(p.slug));
  for (const p of missing) {
    adopt.push({ num: Number(p.num) || 0, slug: p.slug, title: String(p.title).trim().replace(/\s+/g, " "), difficulty: p.difficulty });
  }

  const diffs = [];
  for (const entry of entries) {
    const match = bySlug.get(entry.slug);
    if (!match) {
      diffs.push({ slug: entry.slug, what: "not in the database any more" });
      continue;
    }
    if (normaliseTitle(match.title) !== normaliseTitle(entry.title)) diffs.push({ slug: entry.slug, what: `title -> "${match.title}"` });
    if (match.difficulty !== entry.difficulty) diffs.push({ slug: entry.slug, what: `difficulty ${entry.difficulty} -> ${match.difficulty}` });
  }

  if (!diffs.length && !missing.length && numberConflicts.length === 0) {
    /* Still compare the generated block with what is in the file: if the text
       has drifted (a hand edit, a bad paste) the list is rewritten even though
       the data itself is identical, so the file always matches the script. */
    const expected = adopt
      .slice()
      .sort((a, b) => (a.num && b.num ? a.num - b.num : a.num ? -1 : b.num ? 1 : String(a.title).localeCompare(String(b.title))))
      .map((p) => `      p(${Number(p.num) || 0}, ${jsString(p.slug)}, ${jsString(p.title)}, ${jsString(p.difficulty)}),`);
    const actual = lines.slice(retIndex + 1, end);
    if (JSON.stringify(expected) === JSON.stringify(actual)) {
      console.log("\nNothing to do: the app and the database already agree.");
      await closePool();
      return 0;
    }
    console.log("\nThe data already agrees, but the generated block is not in the shape this script writes.");
  }

  console.log(`\n${diffs.length} title/difficulty differences, ${missing.length} problems missing from the app:`);
  for (const d of diffs.slice(0, 30)) console.log(`  ${d.slug}: ${d.what}`);
  if (diffs.length > 30) console.log(`  ...and ${diffs.length - 30} more`);

  if (numberConflicts.length) {
    console.log(`\n${numberConflicts.length} LeetCode number conflicts - reported, not applied:`);
    for (const c of numberConflicts) console.log(`  ${c}`);
  }

  if (checkOnly) {
    console.log("\n--check: nothing was written.");
    await closePool();
    return 0;
  }

  /* Written in catalog order so the embedded list is also the default order
     the app shows, which is what the API returns for sort=catalog. */
  const ordered = [...adopt].sort((a, b) => {
    if (!a.num && b.num) return 1;
    if (a.num && !b.num) return -1;
    if (a.num !== b.num) return a.num - b.num;
    return String(a.title).localeCompare(String(b.title));
  });

  const generated = ordered.map(
    (p) => `      p(${Number(p.num) || 0}, ${jsString(p.slug)}, ${jsString(p.title)}, ${jsString(p.difficulty)}),`
  );

  const crlf = lines.join("\n").includes("\r\n");
  const updated = [...lines.slice(0, retIndex + 1), ...generated, ...lines.slice(end)];
  fs.writeFileSync(TARGET, updated.join(crlf ? "\r\n" : "\n"), "utf8");

  /* Prove the result is the same list, in the same order, as before. A silent
     truncation here would quietly drop problems from the app. */
  const after = readEmbedded();
  if (after.entries.length !== ordered.length) {
    throw new Error(`the rewrite produced ${after.entries.length} entries but ${ordered.length} were expected - lab-notes.js was left as it was written, check it`);
  }
  const bySlugAfter = new Map(after.entries.map((e) => [e.slug, e]));
  for (const problem of ordered) {
    const written = bySlugAfter.get(problem.slug);
    if (!written) throw new Error(`${problem.slug} is missing from the rewritten list`);
    if (written.title !== problem.title || written.difficulty !== problem.difficulty) {
      throw new Error(`${problem.slug} was written as "${written.title}" (${written.difficulty}) instead of "${problem.title}" (${problem.difficulty})`);
    }
  }

  console.log(`\nRewrote ${generated.length} entries in lab-notes.js and verified all ${after.entries.length}.`);
  console.log("Run `npm run check` and `npm run test:search` afterwards.");
  await closePool();
  return 0;
};

main()
  .then((code) => process.exit(code))
  .catch(async (error) => {
    console.error(`Could not sync the catalog: ${error?.message || error}`);
    try {
      await closePool();
    } catch {
      /* nothing more to do */
    }
    process.exit(1);
  });
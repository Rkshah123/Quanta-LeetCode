/* ---------------------- scripts / sync-catalog-seeds ---------------------- */
/* Rebuilds the problem list embedded in lab-notes.js from the database, so the
   app and the API can never disagree about a title or a difficulty.

   Why this exists
   ---------------
   The app ships a copy of the catalog inside lab-notes.js so it can show a
   problem list with no network at all. That copy is generated from the same
   database, but it was generated by hand once: a few dozen problems now carry
   a different difficulty in the app than in the database, which means
   "Hard" in the app and ?difficulty=Hard on the API return different counts.

   Usage:
     npm run sync:catalog              rewrite lab-notes.js
     npm run sync:catalog -- --check   report differences, change nothing

   The rewrite only replaces the generated entries between "return [" and the
   closing "];" of seedProblems(). Everything else in the file is left alone,
   and the file is not written at all unless something actually differs. */

require("dotenv").config({ path: require("path").join(__dirname, "..", ".env"), quiet: true });

const fs = require("fs");
const path = require("path");
const problemsRepo = require("../db/problems");
const { closePool } = require("../db/pool");

const TARGET = path.join(__dirname, "..", "lab-notes.js");
const checkOnly = process.argv.includes("--check");

const jsString = (value) => JSON.stringify(String(value ?? ""));

/* Whitespace and capitalisation are not worth "fixing" from the database: it
   carries a double space in one title and the wrong case in a few others, and
   copying those in would be a regression dressed up as a sync. A title is only
   replaced when it says something different, not when it merely looks
   different. */
const normaliseTitle = (value) => String(value ?? "").trim().replace(/\s+/g, " ").toLowerCase();

const readEmbedded = () => {
  const source = fs.readFileSync(TARGET, "utf8");
  const lines = source.split(/\r?\n/);
  const start = lines.findIndex((l) => l.includes("const seedProblems = () => {"));
  if (start < 0) throw new Error("seedProblems() was not found in lab-notes.js");
  const retIndex = lines.findIndex((l, i) => i > start && l.trim() === "return [");
  if (retIndex < 0) throw new Error("the generated list was not found in seedProblems()");
  let end = -1;
  for (let i = retIndex + 1; i < lines.length; i += 1) {
    if (/^\s{4}\];\s*$/.test(lines[i])) {
      end = i;
      break;
    }
  }
  if (end < 0) throw new Error("the end of the generated list was not found");

  /* Rows are `p(num, slug, title, difficulty)` for LeetCode and
     `p(num, slug, title, difficulty, platform, url)` for anything else. The
     trailing group is optional so both forms parse with one pattern; a row that
     matches neither is a real problem and is reported rather than skipped. */
  /* The trailing hasDescription is optional so a row written before this
     argument existed still parses - it reads as false, which is what it was. */
  /* The four fixed arguments, then everything else captured whole. Which format a
     row is in is decided by inspecting each remaining token rather than by a
     second regex - otherwise a format change makes the generator unable to read
     the very rows it is meant to be replacing. */
  const ROW = /^p\((-?\d+),\s*(".*?"),\s*(".*?"),\s*("(?:Easy|Medium|Hard)")(?:,\s*([\s\S]*))?\)[,]?$/;
  const PLATFORM_RE = /^"([a-z]+)"$/;

  /* Splits a tail like `[0, 2], true, "codeforces", "https://..."` into its
     top-level tokens, respecting brackets and quotes. */
  const splitTop = (body) => {
    const out = [];
    let depth = 0;
    let quote = null;
    let cur = "";
    for (const ch of body) {
      if (quote) {
        cur += ch;
        if (ch === quote) quote = null;
        continue;
      }
      if (ch === '"' || ch === "'") { quote = ch; cur += ch; continue; }
      if ("[[{(".includes(ch)) depth += 1;
      if ("]})".includes(ch)) depth -= 1;
      if (ch === "," && depth === 0) { out.push(cur.trim()); cur = ""; continue; }
      cur += ch;
    }
    if (cur.trim()) out.push(cur.trim());
    return out;
  };

  /* Reads a row in either order: the arguments after difficulty are classified
     by what they are, not by where they sit. */
  const readTail = (body) => {
    const parsed = { platform: "leetcode", url: "", topicIndices: [], hasDescription: false };
    for (const token of splitTop(body)) {
      if (token === "null") continue;
      if (token === "true") { parsed.hasDescription = true; continue; }
      if (token === "false") { parsed.hasDescription = false; continue; }
      if (token.startsWith("[")) {
        parsed.topicIndices = token
          .replace(/^\[|\]$/g, "")
          .split(",")
          .map((n) => Number(n.trim()))
          .filter(Number.isFinite);
        continue;
      }
      const asPlatform = token.match(PLATFORM_RE);
      if (asPlatform) { parsed.platform = JSON.parse(token); continue; }
      if (token.startsWith('"')) { parsed.url = JSON.parse(token); continue; }
    }
    return parsed;
  };

  const entries = [];
  const unparsed = [];
  for (let i = retIndex + 1; i < end; i += 1) {
    const text = lines[i].trim();
    if (!text || !text.startsWith("p(")) continue;
    const match = text.match(ROW);
    if (!match) {
      unparsed.push(`${i + 1}: ${text.slice(0, 90)}`);
      continue;
    }
    let num = Number(match[1]);
    if (!Number.isFinite(num)) { unparsed.push(`${i + 1}: ${text.slice(0, 90)}`); continue; }
    let slug;
    let title;
    let difficulty;
    try {
      slug = JSON.parse(match[2]);
      title = JSON.parse(match[3]);
      difficulty = JSON.parse(match[4]);
    } catch {
      unparsed.push(`${i + 1}: ${text.slice(0, 90)}`);
      continue;
    }
    entries.push({ line: i, num, slug, title, difficulty, ...readTail(match[5] || "") });
  }
  return { source, lines, retIndex, end, entries, unparsed };
};

const main = async () => {
  console.log("Reading the catalog from the database...");
  const dbProblems = [];
  const pageSize = 100;
  for (let offset = 0; ; offset += pageSize) {
    const page = await problemsRepo.listProblems({ limit: pageSize, offset, sort: "catalog" });
    if (!page.items.length) break;
    dbProblems.push(...page.items);
    if (offset + page.items.length >= page.total) break;
  }
  console.log(`  ${dbProblems.length} problems read (the database reports the catalog as ${pageSize ? dbProblems.length : 0})`);

  const { lines, retIndex, end, entries, unparsed } = readEmbedded();
  console.log(`  lab-notes.js currently embeds ${entries.length} problems`);
  if (unparsed.length) {
    /* A row the parser cannot read would be silently dropped from the rewrite,
       so this stops the run instead. */
    console.error(`  ${unparsed.length} generated row(s) could not be parsed:`);
    for (const line of unparsed.slice(0, 5)) console.error(`    ${line}`);
    throw new Error("lab-notes.js has generated rows this script cannot read; fix them by hand before syncing");
  }

  const bySlug = new Map(dbProblems.map((p) => [p.slug, p]));
  const embeddedBySlug = new Map(entries.map((e) => [e.slug, e]));

  /* Two different kinds of difference, kept apart on purpose.
     - Titles and difficulties: the database is the catalogue of record, so the
       app takes them. Difficulty is what the filters use, so this is the part
       that actually fixes the wrong filter counts.
     - LeetCode numbers: the database is known to be wrong for a few rows
       (percentage-of-letter-in-string is stored as 2278 instead of 1633, and
       two more like it), so the app keeps the number it already has. The
       conflicts are reported instead of being applied. */
  const adopt = [];
  const numberConflicts = [];
  const unknownTopics = new Set();

  const dropped = [];

  for (const entry of entries) {
    const match = bySlug.get(entry.slug);
    if (!match) {
      /* Not in the database. This used to mean "keep it, the database may just
         not have caught up", which was safe while the catalog only ever grew.
         It stopped being safe once the curator started pruning to a cap: a
         pruned problem stayed embedded forever, the embedded list grew past
         the cap, and the file became a copy of itself rather than of the
         database. The database is the catalog of record, so an entry with no
         database row is dropped and reported. */
      dropped.push(entry);
      continue;
    }
    /* Title and difficulty are reconciled below; platform and url always come
       from the database, because they are facts about where a problem lives
       rather than anything the app chose. Carrying the embedded values forward
       would keep a stale "leetcode" on a problem the curator has since
       recorded as coming from another platform. */
    const identity = {
      platform: match.platform || "leetcode",
      url: match.url || "",
      topics: match.topics || [],
      /* Whether this device holds the problem's statement, which is what decides
         whether a mock answer can be marked rather than merely run. */
      hasDescription: match.hasDescription === true
    };

    if (normaliseTitle(match.title) !== normaliseTitle(entry.title)) {
      adopt.push({ ...entry, ...identity, title: String(match.title).trim().replace(/\s+/g, " "), difficulty: match.difficulty });
    } else if (match.difficulty !== entry.difficulty) {
      adopt.push({ ...entry, ...identity, title: entry.title, difficulty: match.difficulty });
    } else {
      adopt.push({ ...entry, ...identity, title: entry.title, difficulty: match.difficulty });
    }
    if ((match.num ?? null) !== entry.num) {
      numberConflicts.push(`${entry.slug}: app ${entry.num} vs database ${match.num ?? "none"} (kept the app's)`);
    }
  }

  const embeddedSlugs = new Set(entries.map((e) => e.slug));
  const missing = dbProblems.filter((p) => !embeddedSlugs.has(p.slug));
  for (const p of missing) {
    /* platform and url travel with the row: the app has to link a Codeforces
       problem to codeforces.com, not to a leetcode.com URL built from a
       Codeforces slug. */
    adopt.push({
      num: Number(p.num) || 0,
      slug: p.slug,
      title: String(p.title).trim().replace(/\s+/g, " "),
      difficulty: p.difficulty,
      platform: p.platform || "leetcode",
      url: p.url || "",
      hasDescription: p.hasDescription === true,
      topics: p.topics || []
    });
  }

  const diffs = [];
  for (const entry of entries) {
    const match = bySlug.get(entry.slug);
    if (!match) {
      diffs.push({ slug: entry.slug, what: "not in the database any more" });
      continue;
    }
    if (normaliseTitle(match.title) !== normaliseTitle(entry.title)) diffs.push({ slug: entry.slug, what: `title -> "${match.title}"` });
    if (match.difficulty !== entry.difficulty) diffs.push({ slug: entry.slug, what: `difficulty ${entry.difficulty} -> ${match.difficulty}` });
  }

  if (dropped.length) {
    console.log(`  dropping ${dropped.length} embedded problem(s) that are no longer in the database:`);
    for (const entry of dropped.slice(0, 8)) console.log(`    ${entry.slug} (${entry.difficulty})`);
    if (dropped.length > 8) console.log(`    ... and ${dropped.length - 8} more`);
  }

  /* Renders one catalog row. Shared by the early-exit comparison and the real
     rewrite so the two can never disagree about the output format - which is
     exactly the bug that let a stale 4-argument form linger.

     Topics are written as indices into the SEED_TOPICS table declared in
     lab-notes.js, never as full labels: ~2,000 rows averaging five topics would
     otherwise add about 200 KB of repeated strings to the file that ships with
     the app. */
    const renderRow = (p) => {
    const base = `      p(${Number(p.num) || 0}, ${jsString(p.slug)}, ${jsString(p.title)}, ${jsString(p.difficulty)}`;
    const isLeetCode = !p.platform || p.platform === "leetcode";
    const platformArg = isLeetCode ? "" : `, ${jsString(p.platform)}, ${jsString(p.url || "")}`;
    const topics = topicIndices(p.topics);
    const topicArg = `, [${topics.join(", ")}]`;
    /* Always written: true or false. A flag that only appears when set cannot
       be told apart from the argument that follows it. */
    const statementArg = p.hasDescription === true ? "true" : "false";
    return `${base}${topicArg}, ${statementArg}${platformArg}),`;
  };
  /* The label list, mirroring SEED_TOPICS in lab-notes.js. If the two ever drift
     the app would label topics with the wrong words, so the script verifies its
     own copy against the file it is writing to. */
  const TOPIC_LABELS = [
    "Arrays", "Strings", "Hashing", "Two Pointers", "Sliding Window", "Prefix Sum",
    "Binary Search", "Linked List", "Stack", "Queue", "Trees", "BST", "Heaps",
    "Graphs", "Backtracking", "Greedy", "Dynamic Programming", "Tries",
    "Bit Manipulation", "Sorting", "Math", "Number Theory", "Advanced Graphs",
    "Probability", "SQL"
  ];
  const TOPIC_INDEX = new Map(TOPIC_LABELS.map((label, i) => [label, i]));

  const topicIndices = (topics) => {
    if (!Array.isArray(topics)) return [];
    const out = [];
    for (const topic of topics) {
      const index = TOPIC_INDEX.get(topic);
      /* A topic that is not in the table is reported rather than dropped in
         silence, because a silently missing topic makes the topic filter lie. */
      if (index === undefined) {
        unknownTopics.add(topic);
        continue;
      }
      out.push(index);
    }
    return out.sort((a, b) => a - b);
  };

  const sortRows = (rows) =>
    [...rows].sort((a, b) => {
      if (!a.num && b.num) return 1;
      if (a.num && !b.num) return -1;
      if (a.num !== b.num) return a.num - b.num;
      return String(a.title).localeCompare(String(b.title));
    });

  if (!diffs.length && !missing.length && numberConflicts.length === 0 && !dropped.length) {
    /* Still compare the generated block with what is in the file: if the text
       has drifted (a hand edit, a bad paste) the list is rewritten even though
       the data itself is identical, so the file always matches the script. */
    const expected = sortRows(adopt).map(renderRow);
    const actual = lines.slice(retIndex + 1, end);
    if (JSON.stringify(expected) === JSON.stringify(actual)) {
      console.log("\nNothing to do: the app and the database already agree.");
      await closePool();
      return 0;
    }
    console.log("\nThe data already agrees, but the generated block is not in the shape this script writes.");
  }

  console.log(`\n${diffs.length} title/difficulty differences, ${missing.length} problems missing from the app:`);
  for (const d of diffs.slice(0, 30)) console.log(`  ${d.slug}: ${d.what}`);
  if (diffs.length > 30) console.log(`  ...and ${diffs.length - 30} more`);

  if (numberConflicts.length) {
    console.log(`\n${numberConflicts.length} LeetCode number conflicts - reported, not applied:`);
    for (const c of numberConflicts) console.log(`  ${c}`);
  }

  if (checkOnly) {
    console.log("\n--check: nothing was written.");
    await closePool();
    return 0;
  }

  /* Written in catalog order so the embedded list is also the default order
     the app shows, which is what the API returns for sort=catalog. */
  const ordered = sortRows(adopt);

  const generated = ordered.map(renderRow);

  if (unknownTopics.size) {
    console.log(`  ${unknownTopics.size} topic label(s) are not in the table in lab-notes.js and cannot be embedded:`);
    for (const label of [...unknownTopics].slice(0, 10)) console.log(`    ${label}`);
    console.log("  Add them to SEED_TOPICS in lab-notes.js, or they will be missing from the offline topic filter.");
  }

  const crlf = lines.join("\n").includes("\r\n");
  const updated = [...lines.slice(0, retIndex + 1), ...generated, ...lines.slice(end)];
  fs.writeFileSync(TARGET, updated.join(crlf ? "\r\n" : "\n"), "utf8");

  /* Prove the result is the same list, in the same order, as before. A silent
     truncation here would quietly drop problems from the app. */
  const after = readEmbedded();
  if (after.entries.length !== ordered.length) {
    throw new Error(`the rewrite produced ${after.entries.length} entries but ${ordered.length} were expected - lab-notes.js was left as it was written, check it`);
  }
  const bySlugAfter = new Map(after.entries.map((e) => [e.slug, e]));
  for (const problem of ordered) {
    const written = bySlugAfter.get(problem.slug);
    if (!written) throw new Error(`${problem.slug} is missing from the rewritten list`);
    if (written.title !== problem.title || written.difficulty !== problem.difficulty) {
      throw new Error(`${problem.slug} was written as "${written.title}" (${written.difficulty}) instead of "${problem.title}" (${problem.difficulty})`);
    }
    /* A non-LeetCode problem must keep its own platform and link, or the app
       would send the user to a leetcode.com URL built from a foreign slug. */
    const expectedPlatform = problem.platform || "leetcode";
    if ((written.platform || "leetcode") !== expectedPlatform) {
      throw new Error(`${problem.slug} was written with platform "${written.platform}" instead of "${expectedPlatform}"`);
    }
    if (expectedPlatform !== "leetcode" && written.url !== (problem.url || "")) {
      throw new Error(`${problem.slug} was written with url "${written.url}" instead of "${problem.url}"`);
    }
  }

  console.log(`\nRewrote ${generated.length} entries in lab-notes.js and verified all ${after.entries.length}.`);
  console.log("Run `npm run check` and `npm run test:search` afterwards.");
  await closePool();
  return 0;
};

main()
  .then((code) => process.exit(code))
  .catch(async (error) => {
    console.error(`Could not sync the catalog: ${error?.message || error}`);
    try {
      await closePool();
    } catch {
      /* nothing more to do */
    }
    process.exit(1);
  });
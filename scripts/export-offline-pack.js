/* Builds offline-pack.js — every statement the database has, shipped with the
   app so statements can be read with no internet, no laptop and no server at
   all. The client loads it lazily, only after both network sources failed.
   Regenerate after an import:  npm run export:offline-pack */
"use strict";

const fs = require("fs");
const path = require("path");

const database = require("../db/pool");

(async () => {
  const rows = await database.query(
    "SELECT slug, description_html FROM problems WHERE description_html IS NOT NULL AND CHAR_LENGTH(TRIM(description_html)) > 50 ORDER BY lc_num"
  );
  const pack = {};
  for (const row of rows) {
    const html = String(row.description_html || "");
    if (html.trim()) pack[row.slug] = html;
  }
  const json = JSON.stringify(pack);
  const banner =
    "/* Generated by scripts/export-offline-pack.js — every statement the\n" +
    "   database has, so the app shows them with no internet at all.\n" +
    "   Regenerate after an import: npm run export:offline-pack */\n";
  const out = path.join(__dirname, "..", "offline-pack.js");
  fs.writeFileSync(out, `${banner}window.QUANTA_OFFLINE_PACK = ${json};\n`, "utf8");
  console.log(
    `offline-pack.js: ${Object.keys(pack).length} statements, ${(json.length / 1024 / 1024).toFixed(1)} MB`
  );
  return 0;
})()
  .then((code) => database.closePool().finally(() => process.exit(code)))
  .catch((error) => {
    console.error(`ERR: ${error.message}`);
    process.exitCode = 1;
    return database.closePool().finally(() => process.exit(1));
  });
